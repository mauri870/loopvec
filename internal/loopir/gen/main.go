// Command capsgen writes the table of methods the simd package provides on each
// vector type, read from the simd_stubs.go of the Go toolchain on the path.
//
// simd_stubs.go lists the methods every supported architecture and vector width
// has in common, which is the contract loopvec can rely on. Reading it, instead
// of writing the rules by hand, keeps loopvec's idea of which operations exist
// for which element types from drifting from the toolchain. The output depends
// on the toolchain's version, which is recorded in its header; the Makefile
// pins one.
//
// Usage:
//
//	capsgen -o caps_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

var out = flag.String("o", "", "output file")

func main() {
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "usage: capsgen -o file.go")
		os.Exit(2)
	}
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "capsgen:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	goroot, err := goEnv("GOROOT")
	if err != nil {
		return err
	}
	version, err := goEnv("GOVERSION")
	if err != nil {
		return err
	}

	path := filepath.Join(goroot, "src", "simd", "simd_stubs.go")
	src, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("%s has no simd package (needs Go 1.27 or later): %w", version, err)
	}
	methods, err := parseMethods(path, src)
	if err != nil {
		return err
	}

	data, err := render(version, methods)
	if err != nil {
		return err
	}
	return os.WriteFile(out, data, 0o644)
}

// parseMethods returns, for each type that has methods in src, the sorted names
// of its exported methods.
func parseMethods(filename string, src []byte) (map[string][]string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), filename, src, 0)
	if err != nil {
		return nil, err
	}
	methods := map[string][]string{}
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 || !fn.Name.IsExported() {
			continue
		}
		receiver, ok := fn.Recv.List[0].Type.(*ast.Ident)
		if !ok {
			continue
		}
		methods[receiver.Name] = append(methods[receiver.Name], fn.Name.Name)
	}
	if len(methods) == 0 {
		return nil, fmt.Errorf("%s declares no methods", filename)
	}
	for _, names := range methods {
		sort.Strings(names)
	}
	return methods, nil
}

var tmpl = template.Must(template.New("caps").Parse(`// Code generated by capsgen from the simd package of {{.Version}}. DO NOT EDIT.

package loopir

// simdMethods lists the methods each simd vector type has on every supported
// architecture.
var simdMethods = map[string]map[string]bool{
{{range .Types}}	"{{.Name}}": {
{{range .Methods}}		"{{.}}": true,
{{end}}	},
{{end}}}
`))

type typeMethods struct {
	Name    string
	Methods []string
}

func render(version string, methods map[string][]string) ([]byte, error) {
	var types []typeMethods
	for name, names := range methods {
		types = append(types, typeMethods{Name: name, Methods: names})
	}
	sort.Slice(types, func(i, j int) bool { return types[i].Name < types[j].Name })

	var buffer bytes.Buffer
	err := tmpl.Execute(&buffer, struct {
		Version string
		Types   []typeMethods
	}{strings.TrimSpace(version), types})
	if err != nil {
		return nil, err
	}
	return format.Source(buffer.Bytes())
}

func goEnv(name string) (string, error) {
	out, err := exec.Command("go", "env", name).Output()
	if err != nil {
		return "", fmt.Errorf("go env %s: %w", name, err)
	}
	return strings.TrimSpace(string(out)), nil
}
